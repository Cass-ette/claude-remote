describe("renderAccessApp (assertion 2)", () => {
  it("defines one self_hosted app on the same hostname with the assetlinks exact-path bypass", () => {
    const app = JSON.parse(renderAccessApp(validConfig()));
    expect(app.name).toBe("Claude Remote Bridge");
    expect(app.domain).toBe("bridge.example.com");
    expect(app.type).toBe("self_hosted");
    expect(app.aud).toBe("0e9a5b2f7dbf4e1b9a17d8e0c3f2a1b0");
    expect(app.app_launcher_visible).toBe(false);
    expect(app.bypass).toEqual([{ type: "exact_path", value: "/.well-known/assetlinks.json" }]);
  });

  it("policy allows exactly the user-supplied email subjects and nothing else", () => {
    const single = JSON.parse(renderAccessApp(validConfig()));
    expect(single.policies).toEqual([
      { name: "owner only", decision: "allow", include: [{ email: { email: "owner@example.com" } }] },
    ]);

    const multi = JSON.parse(
      renderAccessApp(
        validConfig({ subjects: "owner@example.com, partner@example.com" }),
      ),
    );
    expect(multi.policies).toHaveLength(1);
    expect(multi.policies[0]?.include).toEqual([
      { email: { email: "owner@example.com" } },
      { email: { email: "partner@example.com" } },
    ]);
  });

  it("emits strict JSON with no service-token material anywhere", () => {
    const text = renderAccessApp(validConfig());
    expect(() => JSON.parse(text)).not.toThrow();
    expect(text).not.toMatch(/service[-_]?token/i);
    expect(text).not.toMatch(/authorization\s*:\s*bearer/i);
  });

  it("pins allowed_idps when an email IdP is supplied, drops it when not", () => {
    const pinned = JSON.parse(renderAccessApp(validConfig({ emailIdp: "6d4a1c2b-9e8f-4a7b-b3c5-d2e1f0a9b8c7" })));
    expect(pinned.allowed_idps).toEqual(["6d4a1c2b-9e8f-4a7b-b3c5-d2e1f0a9b8c7"]);

    const unpinned = JSON.parse(renderAccessApp(validConfig()));
    expect(unpinned.allowed_idps).toBeUndefined();
  });

  it("committed example template keeps the documented shape", async () => {
    const example = await readFile(ACCESS_APP_EXAMPLE_PATH, "utf8");
    expect(example).toContain('"domain": "{{BRIDGE_PUBLIC_HOST}}"');
    expect(example).toContain('"aud": "{{BRIDGE_CLOUDFLARE_AUD}}"');
    expect(example).toContain("{{CF_ACCESS_INCLUDES}}");
    expect(example).toContain("/.well-known/assetlinks.json");
    expect(example).not.toMatch(/service[-_]?token/i);
  });
});

