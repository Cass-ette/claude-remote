describe("normalizeTunnelConfig rejections (assertion 3)", () => {
  it("rejects any variable that resolves to empty, naming the variable", () => {
    for (const [field, envName] of [
      ["tunnelId", "CF_TUNNEL_ID"],
      ["credentialsFile", "CF_TUNNEL_CREDENTIALS_FILE"],
      ["publicHost", "BRIDGE_PUBLIC_HOST"],
      ["aud", "BRIDGE_CLOUDFLARE_AUD"],
    ] as const) {
      expectRenderError(
        () => normalizeTunnelConfig({ ...VALID, [field]: "" }),
        "EMPTY_VARIABLE",
        new RegExp(envName),
      );
      expectRenderError(
        () => normalizeTunnelConfig({ ...VALID, [field]: undefined }),
        "EMPTY_VARIABLE",
        new RegExp(envName),
      );
    }
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, subjects: "" }),
      "EMPTY_VARIABLE",
      /CF_ACCESS_SUBJECTS/,
    );
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, subjects: [] }),
      "EMPTY_VARIABLE",
      /CF_ACCESS_SUBJECTS/,
    );
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, subjects: "owner@example.com,,partner@example.com" }),
      "EMPTY_VARIABLE",
      /CF_ACCESS_SUBJECTS/,
    );
  });

  it("rejects a second hostname in the public host", () => {
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, publicHost: "bridge.example.com,evil.example.com" }),
      "MULTIPLE_PUBLIC_HOSTS",
      /second hostname|multiple/i,
    );
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, publicHost: "bridge.example.com evil.example.com" }),
      "MULTIPLE_PUBLIC_HOSTS",
      /./,
    );
  });

  it("rejects a non-HTTPS public scheme, normalizes https:// and :443", () => {
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, publicHost: "http://bridge.example.com" }),
      "NON_HTTPS_SCHEME",
      /https/i,
    );
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, publicHost: "ftp://bridge.example.com" }),
      "NON_HTTPS_SCHEME",
      /./,
    );
    expect(normalizeTunnelConfig({ ...VALID, publicHost: "https://Bridge.Example.com:443" }).publicHost).toBe(
      "bridge.example.com",
    );
  });

  it("rejects userinfo, path, query, fragment, non-443 port and non-DNS hosts", () => {
    for (const bad of [
      "user@bridge.example.com",
      "bridge.example.com/path",
      "bridge.example.com?x=1",
      "bridge.example.com#frag",
      "bridge.example.com:8443",
      "not a hostname",
      "localhost",
    ]) {
      expectRenderError(
        () => normalizeTunnelConfig({ ...VALID, publicHost: bad }),
        "INVALID_PUBLIC_HOST",
        /./,
      );
    }
  });

  it("rejects a relative credentials file, bad tunnel id and bad port", () => {
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, credentialsFile: "tunnel-creds.json" }),
      "INVALID_CREDENTIALS_PATH",
      /absolute/i,
    );
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, tunnelId: "../etc/passwd" }),
      "INVALID_TUNNEL_ID",
      /./,
    );
    expectRenderError(() => normalizeTunnelConfig({ ...VALID, port: 80 }), "INVALID_PORT", /./);
    expectRenderError(() => normalizeTunnelConfig({ ...VALID, port: 70000 }), "INVALID_PORT", /./);
  });

  it("rejects subjects that are not plain email addresses", () => {
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, subjects: "not-an-email" }),
      "INVALID_SUBJECT",
      /email/i,
    );
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, subjects: "has space@example.com" }),
      "INVALID_SUBJECT",
      /./,
    );
  });
});

describe("service-token rejection (assertion 3)", () => {
  it("rejects service-token style keys and bearer-style values in inputs", () => {
    expectRenderError(
      () => assertNoServiceTokens({ CF_SERVICE_TOKEN: "v1.abc-def" }),
      "SERVICE_TOKEN_REJECTED",
      /service token/i,
    );
    expectRenderError(
      () => assertNoServiceTokens({ CF_ACCESS_CLIENT_ID: "x.access" }),
      "SERVICE_TOKEN_REJECTED",
      /./,
    );
    expectRenderError(
      () => assertNoServiceTokens({ CF_ACCESS_CLIENT_SECRET: "deadbeef" }),
      "SERVICE_TOKEN_REJECTED",
      /./,
    );
    expectRenderError(
      () => assertNoServiceTokens({ SOME_NOTE: "Authorization: Bearer eyJ..." }),
      "SERVICE_TOKEN_REJECTED",
      /./,
    );
    expect(() =>
      assertNoServiceTokens({
        BRIDGE_PUBLIC_HOST: "bridge.example.com",
        CF_TUNNEL_ID: "abc123",
      }),
    ).not.toThrow();
  });

  it("rejects service tokens arriving through the env file (renderer never accepts them)", () => {
    const poisoned = parseEnvFile(`${TASK34_ENV_FILE}\nCF_ACCESS_CLIENT_ID="x.access"\nCF_ACCESS_CLIENT_SECRET="s3cret"`);
    expectRenderError(
      () => tunnelInputFromEnvFile(poisoned),
      "SERVICE_TOKEN_REJECTED",
      /./,
    );
    expectRenderError(
      () => normalizeTunnelConfig({ ...VALID, subjects: "Authorization: Bearer abc" }),
      "SERVICE_TOKEN_REJECTED",
      /./,
    );
  });
});

