// A1 — rendered config.yml shape (template + renderer)
// ---------------------------------------------------------------------------

describe("renderConfigYml (assertion 1)", () => {
  it("template and rendering carry exactly one hostname mapping to the loopback bridge port", async () => {
    const template = await readFile(CONFIG_TEMPLATE_PATH, "utf8");
    expect(template.match(/- hostname:/g)?.length).toBe(1);
    const yaml = renderConfigYml(validConfig());
    expect(yaml.match(/^\s*-\s*hostname:/gm)?.length).toBe(1);
    expect(yaml).toMatch(/- hostname: bridge\.example\.com\s*\n\s+service: http:\/\/127\.0\.0\.1:43111\b/);
  });

  it("ends with the mandatory http_status:404 catch-all and has exactly two service rules", () => {
    const yaml = renderConfigYml(validConfig());
    expect(yaml.trimEnd().endsWith("- service: http_status:404")).toBe(true);
    expect(yaml.match(/^[ \t]*(?:-[ \t]+)?service:/gm)?.length).toBe(2);
  });

  it("template and rendering contain no originRequest / noTLSVerify overrides", async () => {
    const template = await readFile(CONFIG_TEMPLATE_PATH, "utf8");
    expect(template).not.toContain("originRequest");
    expect(template).not.toContain("noTLSVerify");
    const yaml = renderConfigYml(validConfig());
    expect(yaml).not.toContain("originRequest");
    expect(yaml).not.toContain("noTLSVerify");
  });

  it("forwards only the configured bridge port (never any other loopback port)", () => {
    const yaml = renderConfigYml(validConfig({ port: 45000 }));
    expect(yaml).toContain("service: http://127.0.0.1:45000");
    const loopbackPorts = [...yaml.matchAll(/127\.0\.0\.1:(\d+)/g)].map((m) => m[1]);
    expect(loopbackPorts).toEqual(["45000"]);
  });

  it("carries the tunnel id and absolute credentials file", () => {
    const yaml = renderConfigYml(validConfig());
    expect(yaml).toMatch(/^tunnel: 1b0f8a9e-3c2d-4e5f-9a8b-7c6d5e4f3a2b$/m);
    expect(yaml).toMatch(
      /^credentials-file: \/Users\/tester\/\.cloudflared\/1b0f8a9e-3c2d-4e5f-9a8b-7c6d5e4f3a2b\.json$/m,
    );
  });
});

