describe("tunnelInputFromEnvFile (assertion 4)", () => {
  it("renders end-to-end from the Task 34 env file plus CF_* keys", () => {
    const input = tunnelInputFromEnvFile(parseEnvFile(TASK34_ENV_FILE));
    const yaml = renderConfigYml(normalizeTunnelConfig(input));
    expect(yaml).toMatch(/- hostname: bridge\.example\.com\s*\n\s+service: http:\/\/127\.0\.0\.1:43111/);
    const app = JSON.parse(renderAccessApp(normalizeTunnelConfig(input)));
    expect(app.domain).toBe("bridge.example.com");
    expect(app.policies[0]?.include).toEqual([{ email: { email: "owner@example.com" } }]);
  });

  it("a bare Task 34 env file (no CF_* keys yet) fails naming the missing variables", () => {
    const bare = parseEnvFile(
      [
        'BRIDGE_CLOUDFLARE_TEAM_DOMAIN="myteam.cloudflareaccess.com"',
        'BRIDGE_CLOUDFLARE_AUD="0e9a5b2f7dbf4e1b9a17d8e0c3f2a1b0"',
        'BRIDGE_PUBLIC_HOST="bridge.example.com"',
      ].join("\n"),
    );
    expectRenderError(
      () => normalizeTunnelConfig(tunnelInputFromEnvFile(bare)),
      "EMPTY_VARIABLE",
      /CF_TUNNEL_ID/,
    );
  });

  it("explicit overrides win over file values; unknown keys are tolerated", () => {
    const input = tunnelInputFromEnvFile(parseEnvFile(TASK34_ENV_FILE), {
      publicHost: "override.example.com",
      port: 45000,
      subjects: "someone@example.com",
    });
    const config = normalizeTunnelConfig(input);
    expect(config.publicHost).toBe("override.example.com");
    expect(config.port).toBe(45000);
    expect(config.subjects).toEqual(["someone@example.com"]);
  });
});

