const VALID: TunnelConfigInput = {
  tunnelId: "1b0f8a9e-3c2d-4e5f-9a8b-7c6d5e4f3a2b",
  credentialsFile: "/Users/tester/.cloudflared/1b0f8a9e-3c2d-4e5f-9a8b-7c6d5e4f3a2b.json",
  publicHost: "bridge.example.com",
  port: 43111,
  aud: "0e9a5b2f7dbf4e1b9a17d8e0c3f2a1b0",
  subjects: ["owner@example.com"],
};

function validConfig(overrides: Partial<TunnelConfigInput> = {}): TunnelConfig {
  return normalizeTunnelConfig({ ...VALID, ...overrides });
}

/** Realistic env file: exactly what Task 34's installer writes, plus the
 * cloudflared/Access keys the user appends before rendering. */
const TASK34_ENV_FILE = [
  "# Generated by claude-remote install-launchd — mode 0600, owner-only.",
  "# Loaded by the Bridge at boot via BRIDGE_ENV_FILE (bridge/src/config.ts).",
  'BRIDGE_CLOUDFLARE_TEAM_DOMAIN="myteam.cloudflareaccess.com"',
  'BRIDGE_CLOUDFLARE_AUD="0e9a5b2f7dbf4e1b9a17d8e0c3f2a1b0"',
  'BRIDGE_PUBLIC_HOST="bridge.example.com"',
  "# appended for render-cloudflared-config:",
  'CF_TUNNEL_ID="1b0f8a9e-3c2d-4e5f-9a8b-7c6d5e4f3a2b"',
  'CF_TUNNEL_CREDENTIALS_FILE="/Users/tester/.cloudflared/1b0f8a9e-3c2d-4e5f-9a8b-7c6d5e4f3a2b.json"',
  'CF_ACCESS_SUBJECTS="owner@example.com"',
].join("\n");

function expectRenderError(fn: () => unknown, code: string, messagePattern: RegExp): void {
  let caught: unknown;
  try {
    fn();
  } catch (error) {
    caught = error;
  }
  expect(caught).toBeInstanceOf(RenderError);
  expect((caught as RenderError).code).toBe(code);
  expect((caught as RenderError).message).toMatch(messagePattern);
}

function modeOf(path: string): number {
  return statSync(path).mode & 0o777;
}

const scratchDirs: string[] = [];
afterEach(() => {
  for (const dir of scratchDirs.splice(0)) {
    import("node:fs").then((fs) => fs.rmSync(dir, { recursive: true, force: true }));
  }
});

function scratchHome(): string {
  const dir = mkdtempSync(join(tmpdir(), "cloudflared-render-test-"));
  scratchDirs.push(dir);
  return dir;
}

