// Tests for deploy/scripts/render-cloudflared-config.ts (implementation-plan
// Task 35; spec §5, §10.1, §10.2).
//
// Security heart of this file (each maps to a plan assertion):
//
//   A1. Rendered config.yml: ONE ingress hostname → the loopback Bridge HTTP
//       port, mandatory final `service: http_status:404` catch-all, and NO
//       originRequest/noTLSVerify overrides (origin is plain http loopback).
//   A2. Rendered access-app.json: one self_hosted application on the same
//       hostname, an exact-path bypass limited to
//       /.well-known/assetlinks.json, and an email identity policy listing
//       ONLY the user-supplied Access subjects.
//   A3. The renderer REJECTS: a second hostname, a non-HTTPS public scheme,
//       service-token style inputs anywhere, and any variable that resolves
//       to empty (the error names the variable).
//   A4. The same 0600 env file the launchd installer writes (Task 34)
//       supplies BRIDGE_PUBLIC_HOST / BRIDGE_CLOUDFLARE_AUD / BRIDGE_PORT.

