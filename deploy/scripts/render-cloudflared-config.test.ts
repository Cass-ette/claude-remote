describe("renderTunnelFiles", () => {
  const options = (home: string): RenderOptions => ({ homeDir: home });

  it("writes config.yml and access-app.json with mode 0600 under ~/.cloudflared", () => {
    const home = scratchHome();
    const result = renderTunnelFiles(VALID, options(home));
    const dir = join(home, ".cloudflared");
    expect(result.configYmlPath).toBe(join(dir, "config.yml"));
    expect(result.accessAppPath).toBe(join(dir, "access-app.json"));
    expect(modeOf(result.configYmlPath)).toBe(0o600);
    expect(modeOf(result.accessAppPath)).toBe(0o600);
    expect(existsSync(join(homedir(), ".cloudflared", "config.yml"))).toBe(false);
    const yaml = readFileSync(result.configYmlPath, "utf8");
    expect(yaml).toContain("hostname: bridge.example.com");
  });

  it("dry-run writes nothing", () => {
    const home = scratchHome();
    const logged: string[] = [];
    const result = renderTunnelFiles(VALID, { homeDir: home, dryRun: true, log: (l) => logged.push(l) });
    expect(result.dryRun).toBe(true);
    expect(existsSync(join(home, ".cloudflared"))).toBe(false);
    expect(logged.some((line) => line.includes("config.yml"))).toBe(true);
  });

  it("refuses to write before validation passes (typed error, no files)", () => {
    const home = scratchHome();
    expectRenderError(
      () => renderTunnelFiles({ ...VALID, publicHost: "http://bridge.example.com" }, options(home)),
      "NON_HTTPS_SCHEME",
      /./,
    );
    expect(existsSync(join(home, ".cloudflared"))).toBe(false);
  });
});

describe("parseArgs / cliMain", () => {
  it("rejects unknown flags and missing values with a usage error", () => {
    expectRenderError(() => parseArgs(["--nope"]), "usage", /unknown argument/);
    expectRenderError(() => parseArgs(["--tunnel-id"]), "usage", /requires a value/);
    expect(parseArgs(["--tunnel-id", "abc", "--dry-run"]).tunnelId).toBe("abc");
  });

  it("cliMain renders from the Task 34 env file into a chosen out dir", async () => {
    const home = scratchHome();
    const launchAgents = join(home, "Library", "LaunchAgents");
    mkdirSync(launchAgents, { recursive: true });
    writeFileSync(join(launchAgents, ENV_FILENAME), `${TASK34_ENV_FILE}\n`, { mode: 0o600 });
    const outDir = join(home, "out");

    const code = await cliMain(["--home-dir", home, "--out-dir", outDir]);
    expect(code).toBe(0);
    expect(existsSync(join(outDir, "config.yml"))).toBe(true);
    expect(existsSync(join(outDir, "access-app.json"))).toBe(true);
  });

  it("cliMain surfaces a typed error without writing", async () => {
    const home = scratchHome();
    const launchAgents = join(home, "Library", "LaunchAgents");
    mkdirSync(launchAgents, { recursive: true });
    writeFileSync(join(launchAgents, ENV_FILENAME), `${TASK34_ENV_FILE}\nCF_ACCESS_CLIENT_ID="x"\n`);
    const outDir = join(home, "out");
    await expect(cliMain(["--home-dir", home, "--out-dir", outDir])).rejects.toMatchObject({
      code: "SERVICE_TOKEN_REJECTED",
    });
    expect(existsSync(outDir)).toBe(false);
  });
});
